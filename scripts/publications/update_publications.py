#!/usr/bin/env python3
"""Regenerate the publication lists in index.html from NASA ADS.

Papers are found by ORCID (plus any bibcodes listed in entries.json) and
merged with the hand-kept entries in entries.json:

  match     ids used to pair an ADS record with a hand-kept entry
            (arxiv, doi or title)
  fallback  what is shown when ADS has no matching record
  override  always wins over ADS: venue, contribution, extra_links,
            abstract_html

Everything between the PUBLICATIONS:START and PUBLICATIONS:END markers in
index.html is rewritten; the Theses list and the rest of the page are not.

Usage:
  ADS_API_TOKEN=... python3 scripts/publications/update_publications.py
  python3 scripts/publications/update_publications.py --offline
  python3 scripts/publications/update_publications.py --ads-json saved.json
"""
import argparse
import html
import json
import os
import re
import sys
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ENTRIES = os.path.join(ROOT, "scripts", "publications", "entries.json")
INDEX = os.path.join(ROOT, "index.html")
START = "<!-- PUBLICATIONS:START (generated by scripts/publications/update_publications.py; edit entries.json instead) -->"
END = "<!-- PUBLICATIONS:END -->"
ADS_URL = "https://api.adsabs.harvard.edu/v1/search/query"
FIELDS = "bibcode,title,author,year,pubdate,pub,bibstem,volume,page,page_range,abstract,doi,identifier,doctype"
ALLOWED_TAGS = ("sub", "sup", "i", "em", "b", "strong")


def ads_query(token, q):
    params = urllib.parse.urlencode({"q": q, "fl": FIELDS, "rows": 200, "sort": "date desc"})
    req = urllib.request.Request(f"{ADS_URL}?{params}", headers={"Authorization": f"Bearer {token}"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)["response"]["docs"]


def fetch_ads(cfg, token):
    docs = ads_query(token, f"orcid:{cfg['orcid']}")
    if cfg.get("include_bibcodes"):
        docs += ads_query(token, "bibcode:(" + " OR ".join(cfg["include_bibcodes"]) + ")")
    seen, out = set(), []
    for d in docs:
        if d["bibcode"] not in seen:
            seen.add(d["bibcode"])
            out.append(d)
    return out


def norm_title(t):
    return re.sub(r"[^a-z0-9]+", " ", html.unescape(re.sub(r"<[^>]+>", "", t)).lower()).strip()


def arxiv_id(doc):
    for ident in doc.get("identifier", []):
        m = re.match(r"(?:arXiv:)?(\d{4}\.\d{4,5})(?:v\d+)?$", ident)
        if m:
            return m[1]
    return None


def clean_abstract(text):
    """Escape an ADS abstract but keep simple inline tags like <SUB>."""
    out = html.escape(html.unescape(text), quote=False)
    for tag in ALLOWED_TAGS:
        out = re.sub(rf"&lt;(/?){tag}&gt;", rf"<\1{tag}>", out, flags=re.I)
    return re.sub(r"\s+", " ", out).strip()


def short_name(ads_name):
    last, _, first = ads_name.partition(",")
    initials = " ".join(p[0] + "." for p in re.split(r"[\s.]+", first.strip()) if p)
    return f"{initials} {last.strip()}".strip()


def authors_html(names, me):
    def fmt(n):
        s = html.escape(short_name(n))
        return f'<span class="me">{s}</span>' if n.split(",")[0].strip() == me else s
    if len(names) <= 5:
        return ", ".join(fmt(n) for n in names)
    if names[0].split(",")[0].strip() == me:
        return f"{fmt(names[0])} et al."
    me_name = next((n for n in names if n.split(",")[0].strip() == me), None)
    return f"{fmt(names[0])} et al. (incl. {fmt(me_name)})" if me_name else f"{fmt(names[0])} et al."


def venue(doc):
    year = doc.get("year", "")
    if doc.get("doctype") == "eprint" or "arXiv" in (doc.get("bibstem") or [""])[0]:
        return f"Preprint ({year})"
    stem = (doc.get("bibstem") or [doc.get("pub", "")])[0]
    vol = doc.get("volume")
    page = (doc.get("page_range") or (doc.get("page") or [None])[0] or "").replace("-", "\u2013")
    if vol and page:
        return f"{stem} {vol}, {page} ({year})"
    return f"{doc.get('pub', stem)} ({year})"


def from_ads(doc, me):
    links = []
    ax = arxiv_id(doc)
    if ax:
        links.append({"label": "arXiv", "url": f"https://arxiv.org/abs/{ax}"})
    if doc.get("doi"):
        links.append({"label": "DOI", "url": f"https://doi.org/{doc['doi'][0]}"})
    if not links:
        links.append({"label": "ADS", "url": f"https://ui.adsabs.harvard.edu/abs/{doc['bibcode']}"})
    authors = doc.get("author", [])
    return {
        "title": doc["title"][0],
        "authors_html": authors_html(authors, me),
        "venue": venue(doc),
        "year": int(doc.get("year", 0)),
        "first_author": bool(authors) and authors[0].split(",")[0].strip() == me,
        "links": links,
        "abstract_html": clean_abstract(doc["abstract"]) if doc.get("abstract") else None,
        "_arxiv": ax,
        "_doi": (doc.get("doi") or [None])[0],
    }


def matches(entry, rec):
    m = entry["match"]
    if m.get("arxiv") and m["arxiv"] == rec["_arxiv"]:
        return True
    if m.get("doi") and rec["_doi"] and m["doi"].lower() == rec["_doi"].lower():
        return True
    return bool(m.get("title")) and norm_title(m["title"]) == norm_title(rec["title"])


def merge(cfg, docs):
    me = cfg["me"]
    recs = [from_ads(d, me) for d in docs if d.get("doctype") not in cfg["exclude_doctypes"]]
    papers, used = [], set()
    for entry in cfg["entries"]:
        rec = next((r for i, r in enumerate(recs) if i not in used and matches(entry, r)), None)
        if rec is not None:
            used.add(recs.index(rec))
            paper = dict(rec)
            # Keep the hand-kept links (e.g. ADS) when ADS gives none of its own.
            labels = {l["label"] for l in paper["links"]}
            paper["links"] += [l for l in entry["fallback"].get("links", []) if l["label"] not in labels and l["label"] not in ("Code",)]
            if not paper.get("abstract_html"):
                paper["abstract_html"] = entry["fallback"].get("abstract_html")
        else:
            paper = dict(entry["fallback"])
        ov = entry.get("override", {})
        if "venue" in ov:
            paper["venue"] = ov["venue"]
        if "abstract_html" in ov:
            paper["abstract_html"] = ov["abstract_html"]
        paper["contribution"] = ov.get("contribution")
        paper["links"] = [l for l in paper["links"] if l["label"] != "Code"] + ov.get("extra_links", [])
        papers.append(paper)
    papers += [r for i, r in enumerate(recs) if i not in used]
    papers.sort(key=lambda p: -p["year"])  # stable: keeps hand-kept order within a year
    return papers


def render_item(p):
    links = "".join(f'<a href="{html.escape(l["url"])}">{html.escape(l["label"])}</a>' for l in p["links"])
    lines = [
        "        <li>",
        f'          <span class="pub-title">{clean_abstract(p["title"])}</span>',
    ]
    if p.get("authors_html"):
        lines.append(f'          <span class="pub-authors">{p["authors_html"]}</span>')
    lines.append(f'          <span class="pub-venue">{html.escape(p["venue"], quote=False)}</span>')
    if links:
        lines.append(f'          <span class="pub-links">{links}</span>')
    if p.get("contribution"):
        lines.append(f'          <span class="pub-contrib"><em>My contribution:</em> {html.escape(p["contribution"], quote=False)}</span>')
    if p.get("abstract_html"):
        lines += [
            '          <details class="abstract">',
            "            <summary>Abstract</summary>",
            f'            <p>{p["abstract_html"]}</p>',
            "          </details>",
        ]
    lines.append("        </li>")
    return "\n".join(lines)


def render(papers):
    out = [START]
    for heading, first in (("First-author papers", True), ("Co-authored papers", False)):
        items = [render_item(p) for p in papers if p["first_author"] == first]
        out += [f"      <h3>{heading}</h3>", '      <ul class="pub-list">', *items, "      </ul>", ""]
    out.append("      " + END)
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", action="store_true", help="skip ADS and render the hand-kept entries only")
    ap.add_argument("--ads-json", help="read ADS docs from a saved JSON list instead of the API")
    args = ap.parse_args()

    cfg = json.load(open(ENTRIES, encoding="utf-8"))
    if args.offline:
        docs = []
    elif args.ads_json:
        docs = json.load(open(args.ads_json, encoding="utf-8"))
    else:
        token = os.environ.get("ADS_API_TOKEN")
        if not token:
            sys.exit("ADS_API_TOKEN is not set; nothing changed.")
        docs = fetch_ads(cfg, token)
        if not docs:
            sys.exit("ADS returned no papers for this ORCID; nothing changed.")

    page = open(INDEX, encoding="utf-8").read()
    a, b = page.find(START), page.find(END)
    if a < 0 or b < 0:
        sys.exit("Publication markers not found in index.html")
    new = page[:a] + render(merge(cfg, docs)) + page[b + len(END):]
    if new != page:
        open(INDEX, "w", encoding="utf-8").write(new)
        print("index.html updated")
    else:
        print("no changes")


if __name__ == "__main__":
    main()
